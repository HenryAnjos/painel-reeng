-- =============================================================================
-- Reengajamento SaaS: schema multi-cliente (workspaces).
-- Idempotente: pode rodar num banco vazio ou por cima do schema antigo
-- (experts / envios / config). Dados antigos vao para o workspace "Principal".
-- Rode no SQL Editor do Supabase.
-- =============================================================================

-- ---------- workspaces (cada cliente do SaaS) ----------
create table if not exists workspaces (
  id              uuid primary key default gen_random_uuid(),
  nome            text not null,
  plano           text not null default 'starter',
  api_key_hash    text unique,            -- sha256 hex da chave usada pelo motor
  api_key_prefixo text,                   -- so para exibir (ex.: rk_ab12cd)
  espera_minutos  int  not null default 0,
  dedup_horas     int  not null default 24,
  limite_diario   int  not null default 40,
  intervalo_min   int  not null default 20,
  email_remetente text,
  email_assunto   text,
  criado_em       timestamptz not null default now()
);

-- ---------- usuarios e membros ----------
create table if not exists usuarios (
  id               uuid primary key default gen_random_uuid(),
  email            text not null unique,
  nome             text not null,
  senha_hash       text not null,
  admin_plataforma boolean not null default false,
  criado_em        timestamptz not null default now()
);

create table if not exists membros (
  workspace_id uuid not null references workspaces(id) on delete cascade,
  usuario_id   uuid not null references usuarios(id) on delete cascade,
  papel        text not null default 'leitor' check (papel in ('dono', 'admin', 'leitor')),
  criado_em    timestamptz not null default now(),
  primary key (workspace_id, usuario_id)
);
create index if not exists membros_usuario_idx on membros (usuario_id);

create table if not exists convites (
  id           uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references workspaces(id) on delete cascade,
  email        text not null,
  papel        text not null default 'leitor' check (papel in ('admin', 'leitor')),
  token        text not null unique,
  expira_em    timestamptz not null default now() + interval '7 days',
  aceito_em    timestamptz,
  criado_em    timestamptz not null default now()
);
create index if not exists convites_ws_idx on convites (workspace_id);

-- ---------- experts ----------
create table if not exists experts (
  id             bigint generated by default as identity primary key,
  slug           text not null,
  nome           text,
  texto          text,
  audio_url      text,
  api_id         bigint,
  api_hash       text,
  session_string text,
  canal_telegram boolean not null default true,
  canal_email    boolean not null default true,
  ativo          boolean not null default true
);
alter table experts add column if not exists workspace_id uuid references workspaces(id) on delete cascade;
alter table experts add column if not exists criado_em timestamptz not null default now();
-- sequencia de mensagens do Telegram: [{tipo, texto, arquivo|url, nome}]
-- tipo: texto | imagem | video | audio | voz | arquivo. Vazia = formato
-- antigo (audio_url como voz + texto). O e-mail continua usando "texto".
alter table experts add column if not exists mensagens jsonb not null default '[]'::jsonb;

-- arquivos das mensagens (privado: so o painel e o motor, com a service_role)
insert into storage.buckets (id, name, public, file_size_limit)
values ('midias', 'midias', false, 52428800)
on conflict (id) do nothing;

-- ---------- envios (log) ----------
create table if not exists envios (
  id        bigint generated by default as identity primary key,
  criado_em timestamptz not null default now(),
  user_id   text,
  username  text,
  email     text,
  expert    text,
  canal     text,
  status    text,
  detalhe   text
);
alter table envios add column if not exists workspace_id uuid references workspaces(id) on delete cascade;

-- ---------- migra dados antigos para o workspace "Principal" ----------
do $$
declare ws uuid;
begin
  if exists (select 1 from experts where workspace_id is null)
     or exists (select 1 from envios where workspace_id is null) then
    select id into ws from workspaces order by criado_em limit 1;
    if ws is null then
      insert into workspaces (nome, plano) values ('Principal', 'scale') returning id into ws;
    end if;
    -- herda a config global antiga, se existir
    if to_regclass('public.config') is not null then
      execute format($q$
        update workspaces w set
          espera_minutos  = coalesce(c.espera_minutos, w.espera_minutos),
          dedup_horas     = coalesce(c.dedup_horas, w.dedup_horas),
          limite_diario   = coalesce(c.limite_diario, w.limite_diario),
          intervalo_min   = coalesce(c.intervalo_min, w.intervalo_min),
          email_remetente = coalesce(c.email_remetente, w.email_remetente),
          email_assunto   = coalesce(c.email_assunto, w.email_assunto)
        from (select * from config order by id limit 1) c
        where w.id = %L$q$, ws);
    end if;
    update experts set workspace_id = ws where workspace_id is null;
    update envios  set workspace_id = ws where workspace_id is null;
  end if;
end $$;

alter table experts alter column workspace_id set not null;
alter table envios  alter column workspace_id set not null;

-- slug passa a ser unico por workspace (dois clientes podem ter "Professor")
do $$
declare c text;
begin
  for c in
    select con.conname from pg_constraint con
    join pg_class t on t.oid = con.conrelid
    where t.relname = 'experts' and con.contype = 'u'
      and pg_get_constraintdef(con.oid) = 'UNIQUE (slug)'
  loop
    execute format('alter table experts drop constraint %I', c);
  end loop;
end $$;
create unique index if not exists experts_ws_slug_uk on experts (workspace_id, slug);

-- indices para escala (dashboard, historico e dedup do motor)
create index if not exists envios_ws_criado_idx on envios (workspace_id, criado_em desc);
create index if not exists envios_dedup_idx on envios (workspace_id, expert, canal, status, criado_em desc);

-- ---------- seguranca: so a service_role (servidor) acessa ----------
alter table workspaces enable row level security;
alter table usuarios   enable row level security;
alter table membros    enable row level security;
alter table convites   enable row level security;
alter table experts    enable row level security;
alter table envios     enable row level security;

-- ---------- estatisticas agregadas no banco ----------
create or replace function stats_workspace(p_ws uuid, p_tz text default 'America/Sao_Paulo')
returns jsonb
language sql stable
as $$
  with params as (
    select (now() at time zone p_tz)::date as hoje,
           array['erro','flood','peer_flood','bloqueado','nao_resolvido','sem_sessao','pausado'] as falhas
  ),
  base as (
    select e.expert, e.canal, e.status, (e.criado_em at time zone p_tz)::date as dia
    from envios e
    where e.workspace_id = p_ws
      and e.criado_em >= (date_trunc('month', now() at time zone p_tz) at time zone p_tz)
                         - interval '8 days'
  ),
  dias as (
    select generate_series(p.hoje - 6, p.hoje, interval '1 day')::date as dia from params p
  )
  select jsonb_build_object(
    'hoje', (
      select jsonb_build_object(
        'enviados',  count(*) filter (where status = 'enviado'),
        'falhas',    count(*) filter (where status = any(p.falhas)),
        'ignorados', count(*) filter (where status <> 'enviado' and not status = any(p.falhas)),
        'telegram',  count(*) filter (where status = 'enviado' and canal = 'telegram'),
        'email',     count(*) filter (where status = 'enviado' and canal = 'email'))
      from base, params p where dia = p.hoje),
    'mes', (
      select count(*) from base, params p
      where status = 'enviado' and dia >= date_trunc('month', p.hoje)::date),
    'serie', (
      select coalesce(jsonb_agg(jsonb_build_object(
        'dia', d.dia,
        'enviados', (select count(*) from base b where b.dia = d.dia and b.status = 'enviado'),
        'falhas',   (select count(*) from base b, params p where b.dia = d.dia and b.status = any(p.falhas))
      ) order by d.dia), '[]'::jsonb) from dias d),
    'porExpert', (
      select coalesce(jsonb_agg(x order by x.enviados desc), '[]'::jsonb) from (
        select b.expert,
               count(*) filter (where b.status = 'enviado') as enviados,
               count(*) filter (where b.status = any(p.falhas)) as falhas
        from base b, params p where b.dia = p.hoje group by b.expert
      ) x),
    'experts', (
      select jsonb_build_object(
        'total', count(*),
        'ativos', count(*) filter (where ativo),
        'semSessao', coalesce(jsonb_agg(slug) filter (where ativo and canal_telegram
                                and coalesce(session_string, '') = ''), '[]'::jsonb))
      from experts where workspace_id = p_ws)
  );
$$;

-- visao geral para o admin da plataforma
create or replace function stats_plataforma()
returns table (id uuid, nome text, plano text, criado_em timestamptz,
               membros bigint, experts bigint, envios_mes bigint)
language sql stable
as $$
  select w.id, w.nome, w.plano, w.criado_em,
    (select count(*) from membros m where m.workspace_id = w.id),
    (select count(*) from experts x where x.workspace_id = w.id),
    (select count(*) from envios e where e.workspace_id = w.id and e.status = 'enviado'
       and e.criado_em >= date_trunc('month', now()))
  from workspaces w order by w.criado_em;
$$;

revoke execute on function stats_workspace(uuid, text) from public, anon, authenticated;
revoke execute on function stats_plataforma() from public, anon, authenticated;
